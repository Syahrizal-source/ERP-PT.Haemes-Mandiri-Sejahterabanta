import { NextRequest, NextResponse } from "next/server";
import { z } from "zod";
import { db } from "@/lib/supabase/server";

/* =========================
   PARAM VALIDATION
========================= */

const paramSchema = z.object({
  id: z.string().uuid("ID tidak valid"),
});

/* =========================
   UPDATE SCHEMA
========================= */

const updateSchema = z.object({
  harvest_id: z.string().uuid("Harvest ID tidak valid").optional(),

  harvester_name: z
    .string()
    .min(1, "Nama pemanen wajib diisi")
    .max(100)
    .optional(),

  bunches: z.coerce
    .number()
    .int("Jumlah janjang harus bilangan bulat")
    .min(0, "Jumlah janjang tidak boleh minus")
    .optional(),

  weight_kg: z.coerce.number().min(0, "Berat tidak boleh minus").optional(),

  loose_fruit_kg: z.coerce
    .number()
    .min(0, "Brondolan tidak boleh minus")
    .optional(),
});

type UpdateInput = z.infer<typeof updateSchema>;

/* =========================
   PUT (UPDATE)
========================= */

export async function PUT(
  request: NextRequest,
  context: { params: Promise<{ id: string }> },
): Promise<NextResponse> {
  try {
    const params = await context.params;

    const parsedParams = paramSchema.safeParse(params);

    if (!parsedParams.success) {
      return NextResponse.json(
        { errors: parsedParams.error.flatten() },
        { status: 400 },
      );
    }

    const id: string = parsedParams.data.id;

    const body: unknown = await request.json();
    const parsedBody = updateSchema.safeParse(body);

    if (!parsedBody.success) {
      return NextResponse.json(
        { errors: parsedBody.error.flatten() },
        { status: 400 },
      );
    }

    const input: UpdateInput = parsedBody.data;

    const { data, error } = await db
      .from("harvest_details")
      .update({
        harvest_id: input.harvest_id,
        harvester_name: input.harvester_name,
        bunches: input.bunches,
        weight_kg: input.weight_kg,
        loose_fruit_kg: input.loose_fruit_kg,
      })
      .eq("id", id)
      .select()
      .single();

    if (error) {
      return NextResponse.json({ message: error.message }, { status: 500 });
    }

    return NextResponse.json(data, { status: 200 });
  } catch {
    return NextResponse.json(
      { message: "Invalid request body" },
      { status: 400 },
    );
  }
}

/* =========================
   DELETE
========================= */

export async function DELETE(
  _request: NextRequest,
  context: { params: Promise<{ id: string }> },
): Promise<NextResponse> {
  const params = await context.params;

  const parsedParams = paramSchema.safeParse(params);

  if (!parsedParams.success) {
    return NextResponse.json(
      { errors: parsedParams.error.flatten() },
      { status: 400 },
    );
  }

  const id: string = parsedParams.data.id;

  const { error } = await db.from("harvest_details").delete().eq("id", id);

  if (error) {
    return NextResponse.json({ message: error.message }, { status: 500 });
  }

  return NextResponse.json(
    { message: "Harvest detail berhasil dihapus" },
    { status: 200 },
  );
}
